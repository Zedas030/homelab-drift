#!/bin/bash
# Install or update Homelab-Drift on the controller (e.g. a Raspberry Pi). Run as root.
#
#   sudo ./scripts/install.sh                         install/update (program, users, key, units, timers)
#   sudo ./scripts/install.sh --nginx                 also install the nginx site for the docs (port 8097, config/nginx-site.conf)
#   sudo ./scripts/install.sh --prometheus            also add a scrape job to /etc/prometheus/prometheus.yml (with backup)
#   sudo ./scripts/install.sh --ha-setup              create the dead man's switch automation in Home Assistant (needs HA_TOKEN)
#   sudo ./scripts/install.sh --import-docs FILE      seed annotations.yaml from an existing HTML documentation page
#   sudo ./scripts/install.sh --schedule              only apply scan interval and digest time from config.yaml to the timers
#
# Idempotent. An existing config.yaml, .env or annotations.yaml is never overwritten.
set -euo pipefail

APP=/opt/homelab-drift/app
VENV=/opt/homelab-drift/venv
ETC=/etc/homelab-drift
STATE=/var/lib/homelab-drift
LOGDIR=/var/log/homelab-drift
SVC=homelab-drift
SRC="$(cd "$(dirname "$0")/.." && pwd)"
NGINX=0; PROM=0; HASETUP=0; SCHEDULE_ONLY=0; IMPORT=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --nginx) NGINX=1 ;;
    --prometheus) PROM=1 ;;
    --ha-setup) HASETUP=1 ;;
    --schedule) SCHEDULE_ONLY=1 ;;
    --import-docs) IMPORT="$2"; shift ;;
    *) echo "Unknown option: $1"; exit 2 ;;
  esac
  shift
done
[[ $EUID -eq 0 ]] || { echo "Please run as root (sudo)."; exit 1; }
log() { printf '\e[1;34m==>\e[0m %s\n' "$*"; }

apply_schedule() {
  log "Schedule from $ETC/config.yaml"
  read -r INTERVAL DIGEST < <("$VENV/bin/python" - "$ETC/config.yaml" <<'EOF'
import sys
from homelab_drift.config import load
c = load(sys.argv[1])
print(c.scan_interval_minutes, c.digest_time)
EOF
)
  mkdir -p /etc/systemd/system/$SVC.timer.d /etc/systemd/system/$SVC-digest.timer.d
  cat > /etc/systemd/system/$SVC.timer.d/schedule.conf <<EOF
# Generated by install.sh from $ETC/config.yaml (general.scan_interval_minutes) - run install.sh --schedule after changes
[Timer]
# An empty assignment resets ALL monotonic timers, so all three are set again here
OnUnitActiveSec=
OnBootSec=3min
OnActiveSec=1min
OnUnitActiveSec=${INTERVAL}min
EOF
  cat > /etc/systemd/system/$SVC-digest.timer.d/schedule.conf <<EOF
# Generated by install.sh from $ETC/config.yaml (notify.digest_time) - run install.sh --schedule after changes
[Timer]
OnCalendar=
OnCalendar=*-*-* ${DIGEST}:00
EOF
  systemctl daemon-reload
  systemctl restart $SVC.timer $SVC-digest.timer
  echo "   scan every ${INTERVAL} min, digest daily at ${DIGEST}"
}

if [[ $SCHEDULE_ONLY -eq 1 ]]; then apply_schedule; exit 0; fi

log "Packages"
export DEBIAN_FRONTEND=noninteractive
apt-get install -y -q python3-venv git openssh-client rsync sudo >/dev/null

log "Service user $SVC"
if ! id $SVC >/dev/null 2>&1; then
  useradd --system --home-dir "$STATE" --no-create-home --shell /usr/sbin/nologin --comment "Homelab-Drift" $SVC
fi
install -d -o $SVC -g $SVC -m 755 "$STATE"              # 755: nginx needs to read www/
install -d -o $SVC -g $SVC -m 755 "$STATE/www"
install -d -o $SVC -g $SVC -m 750 "$STATE/state" "$STATE/repo"
install -d -o $SVC -g $SVC -m 700 "$STATE/.ssh"
install -d -o $SVC -g $SVC -m 750 "$LOGDIR"
install -d -o root -g $SVC -m 751 "$ETC"   # 751: you can reach your annotations.yaml without sudo; .env stays 600

log "Program -> $APP"
mkdir -p "$APP"
rsync -a --delete --exclude .git --exclude '__pycache__' --exclude '.pytest_cache' --exclude '.venv' --exclude local \
  "$SRC/" "$APP/"
chmod 755 "$APP"/scripts/*.sh "$APP"/gate/*
[[ -x $VENV/bin/python ]] || python3 -m venv "$VENV"
"$VENV/bin/pip" install -q --upgrade pip >/dev/null
"$VENV/bin/pip" install -q "$APP" >/dev/null
# wrapper: "sudo homelab-drift ..." always runs as the service user (state files keep the right owner)
cat > /usr/local/bin/homelab-drift <<EOF
#!/bin/bash
# Homelab-Drift CLI - switches to the service user $SVC
if [[ \$EUID -eq 0 ]]; then exec runuser -u $SVC -- env SUDO_USER="\${SUDO_USER-}" $VENV/bin/homelab-drift "\$@"; fi
if [[ "\$(id -un)" == "$SVC" ]]; then exec $VENV/bin/homelab-drift "\$@"; fi
echo "Please run with sudo: sudo homelab-drift \$*" >&2; exit 2
EOF
chmod 755 /usr/local/bin/homelab-drift

log "Configuration in $ETC"
if [[ ! -f $ETC/config.yaml ]]; then
  install -o root -g $SVC -m 640 "$APP/config/config.example.yaml" "$ETC/config.yaml"
  IP=$(hostname -I | awk '{print $1}')
  sed -i "s#base_url: \"http://pi.example.local:8097/\"#base_url: \"http://$IP:8097/\"#" "$ETC/config.yaml"
fi
chown root:$SVC "$ETC/config.yaml"; chmod 640 "$ETC/config.yaml"
[[ -f $ETC/.env ]] || install -m 600 "$APP/config/env.example" "$ETC/.env"
chown $SVC:$SVC "$ETC/.env"; chmod 600 "$ETC/.env"
OWNER="${SUDO_USER:-root}"
if [[ ! -f $ETC/annotations.yaml ]]; then
  if [[ -n "$IMPORT" ]]; then
    "$VENV/bin/homelab-drift" import-docs "$IMPORT" --host pi --output "$ETC/annotations.yaml"
  else
    install -m 664 "$APP/config/annotations.example.yaml" "$ETC/annotations.yaml"
  fi
fi
# your file: you (the sudo user) may edit it without sudo, the service reads it
chown "$OWNER:$SVC" "$ETC/annotations.yaml"; chmod 664 "$ETC/annotations.yaml"

log "SSH key of the service"
if [[ ! -f $STATE/.ssh/id_ed25519 ]]; then
  runuser -u $SVC -- ssh-keygen -q -t ed25519 -N "" -C "homelab-drift@$(hostname)" -f "$STATE/.ssh/id_ed25519"
fi
PUB=$(cat "$STATE/.ssh/id_ed25519.pub")

log "Make this host monitorable itself (gate, key valid from 127.0.0.1 only)"
"$APP/scripts/install-host.sh" "$PUB" --from "127.0.0.1,::1" | sed 's/^/   /'

log "systemd units and logrotate"
install -m 644 "$APP"/systemd/*.service "$APP"/systemd/*.timer /etc/systemd/system/
install -m 644 "$APP/config/logrotate" /etc/logrotate.d/homelab-drift
systemctl daemon-reload
systemctl enable $SVC.timer $SVC-digest.timer >/dev/null
apply_schedule

if [[ $NGINX -eq 1 ]]; then
  log "nginx site homelab-drift"
  install -m 644 "$APP/config/nginx-site.conf" /etc/nginx/sites-available/homelab-drift
  ln -sf /etc/nginx/sites-available/homelab-drift /etc/nginx/sites-enabled/homelab-drift
  nginx -t && systemctl reload nginx
fi

if [[ $PROM -eq 1 ]]; then
  PY=/etc/prometheus/prometheus.yml
  log "Prometheus scrape job in $PY"
  if grep -q "job_name: *'\?homelab_drift" "$PY"; then
    echo "   already present"
  else
    # only append when scrape_configs is the last section (otherwise better by hand)
    LAST=$(grep -E '^[A-Za-z_]+:' "$PY" | tail -1)
    if [[ "$LAST" != scrape_configs:* ]]; then
      echo "   scrape_configs is not the last section - please add config/prometheus-scrape.yaml by hand"
    else
      cp -a "$PY" "$PY.bak-$(date +%Y%m%d)-drift"
      { echo; cat "$APP/config/prometheus-scrape.yaml"; } >> "$PY"
      if promtool check config "$PY" >/dev/null; then
        systemctl reload prometheus
        echo "   added, backup $PY.bak-$(date +%Y%m%d)-drift"
      else
        echo "   promtool reports errors - restoring the backup"; cp -a "$PY.bak-$(date +%Y%m%d)-drift" "$PY"; exit 1
      fi
    fi
  fi
fi

if [[ $HASETUP -eq 1 ]]; then
  log "Home Assistant: dead man's switch"
  runuser -u $SVC -- "$VENV/bin/python" "$APP/scripts/ha_setup.py" "$ETC/config.yaml"
fi

log "Done"
echo "   Check:      sudo homelab-drift check"
echo "   First scan: sudo systemctl start $SVC.service   (or: sudo homelab-drift scan)"
grep -q '^HA_TOKEN=.\+' "$ETC/.env" || echo "   NOTE: put HA_TOKEN into $ETC/.env (sudo nano $ETC/.env), otherwise there are no notifications."
